import { createRequire } from "node:module"; import path from "node:path"; import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const { chromium } = createRequire(path.join(here, "../../../runtime/package.json"))("playwright");
const b = await chromium.connectOverCDP(`http://127.0.0.1:62498`);
const s = b.contexts().flatMap((c) => c.pages()).find((p) => /localhost:517\d/.test(p.url()));
const loc = s.locator(`[name="${process.argv[2]}"]`).first();
await loc.click(); await s.keyboard.press("Control+a"); await s.keyboard.press("Delete");
await s.keyboard.insertText(process.argv[3]);
console.log(await loc.inputValue());
await b.close();
