"""Refresh packages/conxa-core/conxa_core/_public_suffixes.py from the Public Suffix List.

    python conxa-cloud/scripts/update_public_suffix.py            # downloads the current list
    python conxa-cloud/scripts/update_public_suffix.py list.dat   # or reads a copy you already have

The list rarely changes in ways that matter here; refresh it a couple of times a year.
"""
from __future__ import annotations

import sys
import urllib.request
from datetime import date
from pathlib import Path

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = Path(__file__).resolve().parents[2] / "packages" / "conxa-core" / "conxa_core" / "_public_suffixes.py"


def _ascii(rule: str) -> str:
    """Hostnames arrive as punycode, so the rules must too (the list itself is written in Unicode)."""
    try:
        return rule.encode("idna").decode("ascii") if not rule.isascii() else rule
    except UnicodeError:
        return rule


def main() -> None:
    if len(sys.argv) > 1:
        raw = Path(sys.argv[1]).read_text("utf-8")
    else:
        with urllib.request.urlopen(URL, timeout=30) as resp:  # noqa: S310 - fixed https URL
            raw = resp.read().decode("utf-8")
    rules = sorted({
        _ascii(line.strip().lower()) for line in raw.splitlines()
        if line.strip() and not line.startswith("//") and " " not in line.strip()
    })
    body = "\n".join(rules)
    assert '"""' not in body and "\\" not in body
    OUT.write_text(
        '"""Public Suffix List snapshot (https://publicsuffix.org, MPL-2.0). Generated by\n'
        "conxa-cloud/scripts/update_public_suffix.py - do not edit by hand.\n"
        f'Snapshot: {date.today().isoformat()}, {len(rules)} rules."""\n\n'
        f'RULES = frozenset("""\n{body}\n""".split())\n',
        encoding="utf-8", newline="\n",
    )
    print(f"wrote {OUT} ({len(rules)} rules)")


if __name__ == "__main__":
    main()
